import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import {
  formatInstallReport,
  offerKitExclude,
  rootDocConfirmers,
} from '../src/lib/install-flow.js';
import {
  rootDocAppendPrompt,
  rootDocReplacePrompt,
  trackedRootDocSkipNotice,
} from '../src/lib/rootdoc.js';

// Task 0124: the root-doc confirmation, the exclude offer and the report that
// init and update share, with the prompt and the warning injected.
function repoWith(trackedDoc) {
  const dir = mkdtempSync(join(tmpdir(), 'agentic-install-flow-'));
  const git = (...a) => execFileSync('git', a, { cwd: dir, stdio: 'ignore' });
  git('init', '-q');
  writeFileSync(join(dir, 'AGENTS.md'), '# Agents\n');
  if (trackedDoc) {
    git('add', 'AGENTS.md');
    git('-c', 'user.email=t@example.com', '-c', 'user.name=T', 'commit', '-qm', 'doc');
  }
  return dir;
}

function recorder(answer = true) {
  const asked = [];
  const warned = [];
  return {
    asked,
    warned,
    ask: async (prompt) => {
      asked.push(prompt);
      return answer;
    },
    warn: (line) => warned.push(line),
  };
}

test('rootDocConfirmers: unattended, an untracked doc is written and a tracked one is skipped with a notice', async () => {
  for (const untrackedReplace of ['allow', 'force-gated']) {
    const tracked = repoWith(true);
    const untracked = repoWith(false);
    try {
      const r = recorder();
      const onTracked = rootDocConfirmers({
        cwd: tracked,
        interactive: false,
        untrackedReplace,
        ...r,
      });
      assert.equal(await onTracked.confirmAppend('AGENTS.md'), false);
      assert.equal(await onTracked.confirmReplace('AGENTS.md'), false);
      assert.deepEqual(r.warned, [
        trackedRootDocSkipNotice('AGENTS.md'),
        trackedRootDocSkipNotice('AGENTS.md'),
      ]);
      const forced = rootDocConfirmers({
        cwd: tracked,
        interactive: false,
        forceRootDoc: true,
        untrackedReplace,
        ...recorder(),
      });
      assert.equal(await forced.confirmAppend('AGENTS.md'), true);
      assert.equal(await forced.confirmReplace('AGENTS.md'), true);
      const onUntracked = rootDocConfirmers({
        cwd: untracked,
        interactive: false,
        untrackedReplace,
        ...recorder(),
      });
      assert.equal(await onUntracked.confirmAppend('AGENTS.md'), true);
      assert.deepEqual(r.asked, []);
    } finally {
      rmSync(tracked, { recursive: true, force: true });
      rmSync(untracked, { recursive: true, force: true });
    }
  }
});

test('rootDocConfirmers: an untracked diverged section is regenerated by init and gated by --force on update', async () => {
  const dir = repoWith(false);
  try {
    const init = rootDocConfirmers({
      cwd: dir,
      interactive: false,
      untrackedReplace: 'allow',
      ...recorder(),
    });
    assert.equal(await init.confirmReplace('AGENTS.md'), true);
    const update = rootDocConfirmers({
      cwd: dir,
      interactive: false,
      untrackedReplace: 'force-gated',
      ...recorder(),
    });
    assert.equal(await update.confirmReplace('AGENTS.md'), false);
    const forcedUpdate = rootDocConfirmers({
      cwd: dir,
      interactive: false,
      force: true,
      forceRootDoc: true,
      untrackedReplace: 'force-gated',
      ...recorder(),
    });
    assert.equal(await forcedUpdate.confirmReplace('AGENTS.md'), true);
    const rootDocOnly = rootDocConfirmers({
      cwd: dir,
      interactive: false,
      forceRootDoc: true,
      untrackedReplace: 'force-gated',
      ...recorder(),
    });
    assert.equal(await rootDocOnly.confirmReplace('AGENTS.md'), false);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('rootDocConfirmers: interactive runs ask with the shared prompts and return the answer', async () => {
  const tracked = repoWith(true);
  const untracked = repoWith(false);
  try {
    const yes = recorder(true);
    const t = rootDocConfirmers({
      cwd: tracked,
      interactive: true,
      untrackedReplace: 'allow',
      ...yes,
    });
    assert.equal(await t.confirmAppend('AGENTS.md'), true);
    assert.equal(await t.confirmReplace('AGENTS.md'), true);
    assert.deepEqual(yes.asked, [
      rootDocAppendPrompt('AGENTS.md', 'tracked'),
      rootDocReplacePrompt('AGENTS.md'),
    ]);

    const init = recorder(false);
    const u = rootDocConfirmers({
      cwd: untracked,
      interactive: true,
      untrackedReplace: 'allow',
      ...init,
    });
    assert.equal(await u.confirmReplace('AGENTS.md'), true);
    assert.deepEqual(init.asked, []);

    const update = recorder(false);
    const v = rootDocConfirmers({
      cwd: untracked,
      interactive: true,
      untrackedReplace: 'force-gated',
      ...update,
    });
    assert.equal(await v.confirmReplace('AGENTS.md'), false);
    assert.equal(update.asked.length, 1);
    assert.match(update.asked[0].message, /AGENTS\.md: managed section diverged on disk/);
    assert.equal(update.asked[0].initialValue, false);
  } finally {
    rmSync(tracked, { recursive: true, force: true });
    rmSync(untracked, { recursive: true, force: true });
  }
});

test('offerKitExclude: unattended it notes the untracked kit files; asked and accepted it writes them', async () => {
  const dir = repoWith(false);
  try {
    mkdirSync(join(dir, '.claude/skills/ad-audit'), { recursive: true });
    writeFileSync(join(dir, '.claude/skills/ad-audit/SKILL.md'), 'kit\n');
    const paths = ['.claude/skills/ad-audit/SKILL.md'];

    const quiet = recorder();
    assert.equal(await offerKitExclude({ cwd: dir, paths, interactive: false, ...quiet }), 0);
    assert.equal(quiet.warned.length, 1);
    assert.match(quiet.warned[0], /^note: 1 kit file\(s\) are untracked in this repo/);

    const declined = recorder(false);
    assert.equal(await offerKitExclude({ cwd: dir, paths, interactive: true, ...declined }), 0);
    assert.equal(declined.asked[0].initialValue, true);

    const accepted = recorder(true);
    assert.equal(await offerKitExclude({ cwd: dir, paths, interactive: true, ...accepted }), 1);
    assert.match(readFileSync(join(dir, '.git/info/exclude'), 'utf8'), /ad-audit/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('formatInstallReport: one line per action, then the root doc, the exclude count and the user-level note', () => {
  const actions = [
    { type: 'created', path: '.claude/skills/a/SKILL.md', agent: 'claude-code' },
    { type: 'migration-removed', path: '.agents/skills/b/SKILL.md', agent: 'codex' },
    { type: 'updated', path: 'WORKFLOW.md' },
    { type: 'something-new', path: 'x' },
  ];
  const rootDocAction = { type: 'appended', path: 'AGENTS.md' };
  assert.deepEqual(
    formatInstallReport({ actions, rootDocAction, excluded: 2, tagAgent: true, userInstall: '/u' }),
    [
      '+ [claude-code] .claude/skills/a/SKILL.md',
      '- [codex] .agents/skills/b/SKILL.md',
      '~ WORKFLOW.md',
      '? x',
      '+ AGENTS.md',
      '! .git/info/exclude (+2)',
      'note: agentic is also installed at the user level (/u); ' +
        'a project install is only needed to pin a version or share it via the repo.',
    ]
  );
  assert.deepEqual(
    formatInstallReport({
      actions: actions.slice(0, 1),
      rootDocAction: { type: 'absent' },
      excluded: 0,
      tagAgent: false,
      userInstall: null,
    }),
    ['+ .claude/skills/a/SKILL.md']
  );
});
